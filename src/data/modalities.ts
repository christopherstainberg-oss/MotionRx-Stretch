export function getModalityById(id: string): Modality | undefined {
  return MODALITIES.find((m) => m.id === id);
}

export function listModalities(opts?: {
  setting?: ModalitySetting | "all";
  timing?: ModalityTiming | "all";
  category?: ModalityCategory | "all";
  query?: string;
}): Modality[] {
  const q = opts?.query?.toLowerCase().trim();
  return MODALITIES.filter((m) => {
    if (opts?.setting && opts.setting !== "all" && m.setting !== opts.setting && m.setting !== "either")
      return false;
    if (opts?.timing && opts.timing !== "all" && !m.timings.includes(opts.timing)) return false;
    if (opts?.category && opts.category !== "all" && m.category !== opts.category) return false;
    if (q) {
      const hay = [m.name, m.plainLanguage, m.tags.join(" "), m.clinicalIntent].join(" ").toLowerCase();
      if (!hay.includes(q)) return false;
    }
    return true;
  });
}

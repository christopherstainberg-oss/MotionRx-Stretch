/**
 * Generate src/data/curated-movement-videos.ts from extracted PhysioPath map.
 */
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const curated = JSON.parse(
  fs.readFileSync(path.join(__dirname, "_physiopath-curated-videos.json"), "utf8")
);

const entries = Object.entries(curated)
  .map(
    ([k, v]) =>
      `  ${JSON.stringify(k)}: { youtubeId: ${JSON.stringify(v.id)}, institution: ${JSON.stringify(v.ch)} }`
  )
  .join(",\n");

const channels = [...new Set(Object.values(curated).map((v) => v.ch))].sort();

const out = `/**
 * PhysioPath curated movement → institutional YouTube demonstrations.
 * Every id was oEmbed-verified against publisher author_name (not search snippets).
 * Ported from physiopath src/ui/1-render.js CURATED_VIDEOS.
 *
 * HARD RULES (PhysioPath YouTube management):
 * - Publisher bar only (hospital / health system / NHS / clinic group) — not personal brands
 * - No YouTube search fallback — unmatched movements show no video
 * - Synonyms share verified ids; do not invent new ids without oEmbed re-check
 * - VIDEO_VERIFIED stamps when the set was last confirmed live
 *
 * Auto-generated by scripts/gen-curated-movement-videos.mjs
 */

export const VIDEO_VERIFIED = "July 2026";

export type CuratedMovementVideo = {
  youtubeId: string;
  institution: string;
};

export const CURATED_MOVEMENT_VIDEOS: Record<string, CuratedMovementVideo> = {
${entries}
};

/** Unique publisher names from the curated map (for allowlist expansion) */
export const CURATED_PUBLISHERS: string[] = ${JSON.stringify(channels, null, 2)};
`;

const dest = path.join(__dirname, "../src/data/curated-movement-videos.ts");
fs.writeFileSync(dest, out);
console.log("Wrote", dest, Object.keys(curated).length, "keys,", channels.length, "publishers");

/**
 * Compile extracted PhysioPath program JSON into MotionRx TypeScript modules.
 */
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const raw = JSON.parse(
  fs.readFileSync(path.join(__dirname, "_physiopath-program-raw.json"), "utf8")
);

function revive(v) {
  if (v && typeof v === "object" && v.__re != null) {
    return new RegExp(v.__re, v.__flags || "i");
  }
  if (Array.isArray(v)) return v.map(revive);
  if (v && typeof v === "object") {
    const o = {};
    for (const [k, val] of Object.entries(v)) o[k] = revive(val);
    return o;
  }
  return v;
}

const data = revive(raw);

function regSource(re) {
  if (re instanceof RegExp) return re.source;
  if (re && re.__re) return re.__re;
  return String(re);
}

function esc(s) {
  return String(s).replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$\{/g, "\\${");
}

function emitVariant(v) {
  const parts = [
    `k: ${JSON.stringify(v.k)}`,
    `label: ${JSON.stringify(v.label)}`,
    `sub: ${JSON.stringify(v.sub || "")}`,
  ];
  if (v.scale != null) parts.push(`scale: ${v.scale}`);
  if (v.note) parts.push(`note: ${JSON.stringify(v.note)}`);
  if (v.freq) parts.push(`freq: ${JSON.stringify(v.freq)}`);
  if (v.pick) parts.push(`pick: /${regSource(v.pick)}/i`);
  if (v.ph) parts.push(`ph: ${JSON.stringify(v.ph)}`);
  return `{ ${parts.join(", ")} }`;
}

function emitPlan(p) {
  const parts = [
    `re: /${regSource(p.re)}/i`,
    `label: ${JSON.stringify(p.label)}`,
    `total: ${p.total}`,
    `freq: ${JSON.stringify(p.freq || "")}`,
    `note: ${JSON.stringify(p.note || "")}`,
    `ph: ${JSON.stringify(p.ph)}`,
  ];
  if (p.generic) parts.push(`generic: true`);
  if (p.postop === true) parts.push(`postop: true`);
  if (p.postop === false) parts.push(`postop: false`);
  if (p.variants?.length) {
    parts.push(`variants: [\n    ${p.variants.map(emitVariant).join(",\n    ")}\n  ]`);
  }
  return `{\n  ${parts.join(",\n  ")}\n}`;
}

function emitFocus(f) {
  const adds = (f.add || [])
    .map(
      (a) =>
        `{ p: ${a.p}, n: ${JSON.stringify(a.n)}, d: ${JSON.stringify(a.d || "")}, c: ${JSON.stringify(a.c || "")}${
          a.tags ? `, tags: ${JSON.stringify(a.tags)}` : ""
        } }`
    )
    .join(",\n    ");
  return `{\n  re: /${regSource(f.re)}/i,\n  focus: ${JSON.stringify(f.focus || "")},\n  add: [\n    ${adds}\n  ]\n}`;
}

function emitSport(s) {
  const adds = (s.add || [])
    .map(
      (a) =>
        `{ p: ${a.p}, n: ${JSON.stringify(a.n)}, d: ${JSON.stringify(a.d || "")}, c: ${JSON.stringify(a.c || "")}${
          a.tags ? `, tags: ${JSON.stringify(a.tags)}` : ""
        } }`
    )
    .join(",\n    ");
  return `{\n  re: /${regSource(s.re)}/i,\n  label: ${JSON.stringify(s.label || "")},\n  note: ${JSON.stringify(s.note || "")},\n  add: [\n    ${adds}\n  ]\n}`;
}

// Normalize ladders: phase-index keys as strings of numbers or arrays
function emitLadder(name, ladder) {
  // BALANCE_LADDER etc are objects keyed by phase number
  return `export const ${name} = ${JSON.stringify(ladder, null, 2)} as const;`;
}

const header = `/**
 * PhysioPath program-creation catalog — ported for MotionRx Stretch.
 * Educational timelines only; a treating clinician/surgeon protocol always overrides.
 *
 * Auto-generated by scripts/gen-program-creation-data.mjs from physiopath engine.js.
 * Do not hand-edit large plan tables — re-run the extractor + generator instead.
 */

export type PhaseTuple = [
  title: string,
  weekStart: number,
  weekEnd: number,
  goal: string,
  criteria: string,
  restrict: string
];

export type PlanVariant = {
  k: string;
  label: string;
  sub: string;
  scale?: number;
  note?: string;
  freq?: string;
  pick?: RegExp;
  ph?: PhaseTuple[];
};

export type RehabPlanDef = {
  re: RegExp;
  label: string;
  total: number;
  freq: string;
  note: string;
  ph: PhaseTuple[];
  generic?: boolean;
  /** true = post-op only; false = non-surgical only; undefined = either */
  postop?: boolean;
  variants?: PlanVariant[];
};

export type InjuryFocusDef = {
  re: RegExp;
  focus: string;
  add: Array<{ p: number; n: string; d: string; c: string; tags?: string[] }>;
};

export type TrackId = "acute" | "chronic";
`;

const trackTpl = `export const PROGRAM_TEMPLATE: Record<TrackId, {
  total: number;
  focus: string;
  phases: Array<{ title: string; goal: string }>;
}> = ${JSON.stringify(data.TEMPLATE, null, 2)};

export const PHASE_CRITERIA: Record<TrackId, string[]> = ${JSON.stringify(data.PHASE_CRITERIA, null, 2)};

/** Default exercise count targets per phase before time-budget scaling */
export const PHASE_TARGET = ${JSON.stringify(data.PHASE_TARGET)} as const;
`;

const xcut = `export const XCUT_VARIANTS: PlanVariant[] = [
  ${data.XCUT_VARIANTS.map(emitVariant).join(",\n  ")}
];

export const PACE_BASE_VARIANTS: PlanVariant[] = [
  ${data.PACE_VARIANTS.filter((v) =>
    ["standard", "accelerated", "conservative"].includes(v.k)
  )
    .map(emitVariant)
    .join(",\n  ")}
];

/** Pace options + cross-cutting context variants (PhysioPath planVariants) */
export const PACE_VARIANTS: PlanVariant[] = [
  ...PACE_BASE_VARIANTS,
  ...XCUT_VARIANTS,
];
`;

const domain = `export const DOMAIN_FALLBACK: Record<string, RehabPlanDef> = {
${Object.entries(data.DOMAIN_FALLBACK)
  .map(([k, p]) => `  ${JSON.stringify(k)}: ${emitPlan(p)}`)
  .join(",\n")}
};
`;

const plans = `export const REHAB_PLANS: RehabPlanDef[] = [
${data.REHAB_PLANS.map(emitPlan).join(",\n")}
];
`;

const focus = `export const INJURY_FOCUS: InjuryFocusDef[] = [
${data.INJURY_FOCUS.map(emitFocus).join(",\n")}
];
`;

const ladders = `${emitLadder("BALANCE_LADDER", data.BALANCE_LADDER)}

${emitLadder("AGILITY_LADDER", data.AGILITY_LADDER)}

${emitLadder("FALLS_LADDER", data.FALLS_LADDER)}

export type SportDemandDef = {
  re: RegExp;
  label: string;
  note: string;
  add: Array<{ p: number; n: string; d: string; c: string; tags?: string[] }>;
};

export const SPORT_DEMANDS: SportDemandDef[] = [
${data.SPORT_DEMANDS.map(emitSport).join(",\n")}
];
`;

const outDir = path.join(__dirname, "../src/data");
const outFile = path.join(outDir, "program-creation-catalog.ts");
fs.writeFileSync(
  outFile,
  [header, trackTpl, xcut, domain, plans, focus, ladders].join("\n")
);
console.log("Wrote", outFile, fs.statSync(outFile).size, "bytes");
